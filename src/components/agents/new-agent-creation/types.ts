import type { CustomAgentDefinition } from '@claude-code-best/builtin-tools/tools/AgentTool/loadAgentsDir.js'
import type { AgentMemoryScope } from '@claude-code-best/builtin-tools/tools/AgentTool/agentMemory.js'
import type { SettingSource } from '../../../utils/settings/constants.js'

/**
 * Mutable state passed between steps of the "new agent" wizard.
 * Fields are filled in progressively; `finalAgent` is composed by the Color step before confirmation.
 */
export type AgentWizardData = {
  systemPrompt?: string // final system prompt
  agentType?: string // agent type slug (directory name)
  generationPrompt?: string // full description the user entered in "generate" mode
  selectedTools?: string[] // restrict available tools; undefined means all
  whenToUse?: string // "when to use" description (whenToUse)
  location?: SettingSource // where it is saved: project or personal settings
  selectedModel?: string // override the default model (optional)
  selectedColor?: string // terminal highlight color (optional)
  wasGenerated?: boolean // whether the config was generated by the model in one step
  method?: 'generate' | 'manual' // creation path: generated vs manual
  isGenerating?: boolean // generation request in flight (used for UI debounce)
  generatedAgent?: {
    identifier: string // agentType candidate returned by the generator
    whenToUse: string // description returned by the generator
    systemPrompt: string // system prompt returned by the generator
  }
  selectedMemory?: AgentMemoryScope // memory scope chosen in the Memory step
  finalAgent?: CustomAgentDefinition // draft of the full agent definition before confirming save
}
