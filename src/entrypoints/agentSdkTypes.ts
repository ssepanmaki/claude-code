/**
 * A scheduled task from `<dir>/.claude/scheduled_tasks.json`.
 * @internal
 */
export type CronTask = {
  id: string
  cron: string
  prompt: string
  createdAt: number
  recurring?: boolean
}

/**
 * Cron scheduler tuning knobs (jitter + expiry). Sourced at runtime from the
 * `tengu_kairos_cron_config` GrowthBook config in CLI sessions; daemon hosts
 * pass this through `watchScheduledTasks({ getJitterConfig })` to get the
 * same tuning.
 * @internal
 */
export type CronJitterConfig = {
  recurringFrac: number
  recurringCapMs: number
  oneShotMaxMs: number
  oneShotFloorMs: number
  oneShotMinuteMod: number
  recurringMaxAgeMs: number
}

/** Session hook event names (consistent with `HOOK_EVENTS` / the settings schema). */
export type HookEvent = (typeof HOOK_EVENTS)[number] // corresponds item by item to `coreSchemas.HOOK_EVENTS`

/** Enum of process exit reasons used by `SessionEnd` hooks and others. */
export type ExitReason = (typeof EXIT_REASONS)[number] // corresponds item by item to `coreSchemas.EXIT_REASONS`
